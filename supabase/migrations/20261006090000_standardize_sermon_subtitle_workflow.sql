insert into public.sermon_subtitle_knowledge
  (church_id, knowledge_type, wrong_text, correct_text, context_hint, speaker, source_draft_id, source_segment_index, verified, active)
select
  d.church_id,
  'approved_example',
  left((select string_agg(replace(coalesce(cue->>'text',''), E'\n', ' '), ' ' order by ord)
        from jsonb_array_elements(coalesce(s.cues, '[]'::jsonb)) with ordinality as x(cue, ord)), 12000),
  left((select string_agg(replace(coalesce(cue->>'text',''), E'\n', ' '), ' ' order by ord)
        from jsonb_array_elements(coalesce(s.reviewed_cues, '[]'::jsonb)) with ordinality as x(cue, ord)), 12000),
  '已正式發布的講道字幕片段',
  d.speaker,
  s.draft_id,
  s.segment_index,
  true,
  true
from public.sermon_subtitle_segments s
join public.sermon_social_drafts d on d.id = s.draft_id
join public.youtube_caption_publications p on p.draft_id = s.draft_id and p.status = 'published'
where s.review_status = 'completed'
  and jsonb_array_length(coalesce(s.reviewed_cues, '[]'::jsonb)) > 0
on conflict (source_draft_id, source_segment_index)
  where knowledge_type = 'approved_example'
do nothing;

do $block$
begin
  perform cron.unschedule(jobid)
  from cron.job
  where jobname = 'sermon-subtitle-proofreading';

  perform cron.schedule(
    'sermon-subtitle-proofreading',
    '*/2 * * * *',
    $job$
    with candidate as (
      select draft_id, segment_index
      from public.sermon_subtitle_segments
      where status = 'completed'
        and coalesce(review_status, 'pending') <> 'completed'
      order by updated_at, segment_index
      limit 1
    )
    select net.http_post(
      url := (select decrypted_secret from vault.decrypted_secrets where name = 'pastoral-care-project-url') || '/functions/v1/youtube-oauth',
      headers := jsonb_build_object(
        'content-type', 'application/json',
        'x-cron-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'pastoral-care-cron-secret')
      ),
      body := jsonb_build_object(
        'action', 'rewrite_subtitle_segment',
        'church', 'M+',
        'draftId', candidate.draft_id,
        'segmentIndex', candidate.segment_index
      ),
      timeout_milliseconds := 120000
    )
    from candidate;
    $job$
  );
end
$block$;
