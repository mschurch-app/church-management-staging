create table if not exists public.sermon_subtitle_knowledge (
  id bigint generated by default as identity primary key,
  church_id text not null default 'M+',
  knowledge_type text not null check (knowledge_type in ('glossary','correction','speaker_term','approved_example')),
  wrong_text text,
  correct_text text not null,
  context_hint text,
  speaker text,
  source_draft_id uuid references public.sermon_social_drafts(id) on delete set null,
  source_segment_index integer check (source_segment_index is null or source_segment_index >= 0),
  verified boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.sermon_subtitle_knowledge enable row level security;
revoke all on public.sermon_subtitle_knowledge from anon, authenticated;
grant all on public.sermon_subtitle_knowledge to service_role;

create index if not exists sermon_subtitle_knowledge_lookup_idx
  on public.sermon_subtitle_knowledge (church_id, active, verified, knowledge_type, updated_at desc);

create unique index if not exists sermon_subtitle_knowledge_term_unique_idx
  on public.sermon_subtitle_knowledge (church_id, knowledge_type, coalesce(wrong_text, ''), correct_text)
  where knowledge_type <> 'approved_example';

create unique index if not exists sermon_subtitle_knowledge_example_unique_idx
  on public.sermon_subtitle_knowledge (source_draft_id, source_segment_index)
  where knowledge_type = 'approved_example';

